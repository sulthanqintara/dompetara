import assert from "node:assert/strict";
import { QueryClient } from "@tanstack/react-query";
import { createLedgerStore } from "../src/features/ledger/ledger-store.ts";
import { emptyLedger } from "../src/features/ledger/ledger.ts";
import { ledgerQuery } from "../src/features/ledger/query.ts";
import type { LedgerState } from "../src/features/ledger/api.ts";

const initial = { initialState: { data: emptyLedger(), version: 1 }, name: "Test", email: "test@example.com", initialTimeZone: "UTC", initialMonth: "2026-10" };
const client = new QueryClient();
let next: LedgerState = { data: emptyLedger(), version: 2, notice: "Saved", changes: { before: [], after: [], invalidateTransactions: false } };
let failure: unknown;
let calls = 0;
let release: (() => void) | undefined;
const versions: number[] = [];
const api = {
  async fetchLedger() { if (failure) throw failure; return next; },
  async saveLedger(_payload: Record<string, unknown>, version: number) {
    calls++; versions.push(version);
    if (failure) throw failure;
    await new Promise<void>((resolve) => { release = resolve; });
    return next;
  },
};
const store = createLedgerStore(initial, client, api);
const other = createLedgerStore({ ...initial, name: "Other" }, new QueryClient(), api);
const serverSnapshot = store.getInitialState();
assert.equal(serverSnapshot.balancesVisible, false);
assert.deepEqual(serverSnapshot.period, { month: "2026-10" });
store.getState().setBalancesVisible((visible) => !visible);
store.getState().setCurrency("USD");
assert.equal(other.getState().balancesVisible, false);
assert.equal(other.getState().currency, "IDR");
assert.equal(serverSnapshot.balancesVisible, false);
store.getState().setTimeZone("Asia/Jakarta", "2026-11");
assert.deepEqual(store.getState().period, { month: "2026-11" });
store.getState().setPeriod({ start: "2026-01-01", end: "2026-10-29" });
store.getState().setTimeZone("UTC", "2026-10");
assert.deepEqual(store.getState().period, { start: "2026-01-01", end: "2026-10-29" });
const related = [{ id: "entry", kind: "expense" as const, date: "2026-10-29", wallet: "wallet", currency: "IDR" as const, amount: 100, title: "Test", category: "", description: "" }];
store.getState().setEditor({ type: "entry", entry: related[0], relatedEntries: related });
assert.equal(store.getState().data.entries, related);
const query = ledgerQuery({ month: "2026-10" }, "UTC", "IDR");
const key = ["ledger", "transactions", query];
client.setQueryData(key, { query, version: 1, result: { rows: [], related: [], total: 0, page: 1, pages: 1, start: 0, end: 0 } });
const save = store.getState().save;
const saving = save({ action: "entry" });
assert.equal(store.getState().pending, true);
assert.equal(await save({}), false);
await store.getState().reload();
assert.equal(calls, 1);
release!();
assert.equal(await saving, true);
assert.equal(store.getState().version, 2);
assert.equal(client.getQueryData<{ version: number }>(key)!.version, 2, "Confirmed saves patch the query cache");
assert.equal(store.getState().revision, 1);
assert.equal(store.getState().pending, false);
assert.equal(store.getState().data.entries, related);
assert.equal(store.getState().notice, "Saved");
assert.equal(store.getState().save, save);
assert.deepEqual(versions, [1]);
failure = new Error("Conflict", { cause: 409 });
assert.equal(await save({}), false);
assert.equal(store.getState().conflict, true);
assert.equal(store.getState().error, "Conflict");
assert.equal(await save({}), false);
assert.equal(calls, 2);
await store.getState().reload();
assert.equal(store.getState().conflict, true);
assert.equal(store.getState().pending, false);
failure = undefined;
next = { data: emptyLedger(), version: 4 };
await store.getState().reload();
assert.equal(store.getState().version, 4);
assert.equal(client.getQueryState(key)!.isInvalidated, true, "Reload invalidates ledger queries");
assert.equal(store.getState().conflict, false);
assert.equal(store.getState().reloading, false);
assert.equal(store.getState().editor?.type, "entry");
assert.equal(store.getState().data.entries, related);
assert.equal(store.getState().error, "");
store.getState().setEditor(() => undefined);
assert.deepEqual(store.getState().data.entries, []);
failure = new Error("Connection lost");
assert.equal(await save({}), false);
assert.equal(store.getState().pending, false);
assert.equal(store.getState().conflict, false);
assert.equal(store.getState().error, "Connection lost");
assert.equal(versions.at(-1), 4, "Writes use the latest loaded version");
failure = "Unexpected provider rejection";
assert.equal(await save({}), false);
assert.equal(store.getState().error, "Connection lost. Please try again.");
assert.equal(store.getState().conflict, false);
assert.equal(store.getState().pending, false);
assert.equal(other.getState().version, 1);
client.clear();
console.log("Ledger store checks passed: isolated instances, initial snapshots, functional setters, timezone/period, editor preservation, save guards, conflicts and reload.");
