import assert from "node:assert/strict";
import { emptyLedger, type Entry, type Ledger } from "../src/features/ledger/ledger.ts";
import { initialEntryFields, changeSourceCurrency, changeSourceWallet, destinationWallets, entryCategories, initialTransactionDetails } from "../src/features/ledger/entry-editor.ts";
import { entryPayload, walletPayload } from "../src/features/ledger/editor-payload.ts";
import { initialTransferFields, transferConversion } from "../src/features/ledger/transfer-editor.ts";
import { draftSchema, type Extraction } from "../src/features/receipts/receipts.ts";
import { localDate } from "../src/features/ledger/format.ts";

const data: Ledger = { ...emptyLedger(), wallets: [
  { id: "bank", name: "Bank", currencies: ["IDR", "USD"] }, { id: "cash", name: "Cash", currencies: ["IDR"] },
] };
const now = new Date("2026-10-01T12:34:56Z");
const entry: Entry = { id: "entry", kind: "expense", date: now.toISOString(), wallet: "bank", currency: "IDR", amount: 1234, title: "Lunch", category: "Archived", description: "Personal note" };
const details = { receiptNumber: null, keepItems: false, items: [], adjustments: [] };
const draft = draftSchema.parse({ documentKind: "receipt", merchant: "Store", date: null, time: null, currency: null, receiptNumber: null, total: null, items: [], adjustments: [], warnings: [] });
const initial = initialEntryFields(data, undefined, undefined, now);
assert.deepEqual(initial, { amount: "", date: localDate(now), currency: "IDR", toCurrency: "IDR", wallet: "bank", toWallet: "" });
assert.equal(initialEntryFields(data, entry).amount, "12.34");
assert.equal(initialEntryFields(data, entry).date, localDate(now));
assert.equal(initialEntryFields(data, undefined, draft).currency, "", "Unconfirmed receipt currency remains blank");
assert.equal(initialEntryFields(data, undefined, draft).wallet, "");
assert.equal(initialEntryFields(data, undefined, draft).date, "T");
assert.equal(initialEntryFields(data, undefined, { ...draft, suggestedWallet: { walletId: "cash", reason: "Visible payment source" } }).wallet, "cash");
const selected = { ...initial, toWallet: "bank" };
assert.equal(changeSourceWallet(selected, "bank").toWallet, "");
assert.equal(changeSourceWallet({ ...selected, toCurrency: "USD" }, "bank").toWallet, "bank", "Same wallet may receive another currency");
assert.equal(changeSourceCurrency({ ...selected, currency: "USD" }, data, "IDR").toWallet, "");
assert.equal(changeSourceCurrency(initial, data, "CAD").wallet, "");
assert.deepEqual(destinationWallets(data, initial).map((wallet) => wallet.id), ["cash"]);
assert.deepEqual(destinationWallets(data, { ...initial, toCurrency: "USD" }).map((wallet) => wallet.id), ["bank"]);
assert.equal(entryCategories(data, "expense", entry)[0], "Archived");
assert.equal(initialTransactionDetails({ ...entry, details }, draft), details);
assert.deepEqual(initialTransactionDetails(undefined, draft), details);

const values = { kind: "expense", date: localDate(now), amount: "12.34", title: "Lunch", category: "Archived", details: JSON.stringify(details), newCategory: "false" };
const saved = entryPayload(values, entry);
assert.equal(saved.date, entry.date, "Unchanged minute preserves original seconds");
assert.equal(saved.id, entry.id);
assert.equal(saved.action, "entry");
assert.deepEqual(saved.details, details);
assert.equal(saved.newCategory, false);
assert.equal(entryPayload({ ...values, date: "2026-10-02T10:00" }, entry).date, new Date("2026-10-02T10:00").toISOString());
assert.throws(() => entryPayload({ ...values, date: "invalid" }), /valid date/);
assert.throws(() => entryPayload({ ...values, details: "broken" }), SyntaxError);
assert.throws(() => entryPayload({ ...values, details: JSON.stringify({ ...details, keepItems: true }) }), /Add items/);
const extraction: Extraction = { importId: "00000000-0000-4000-8000-000000000001", fingerprint: "a".repeat(64), method: "ai", draft };
const imported = entryPayload({ ...values, newCategory: "true" }, undefined, extraction);
assert.equal(imported.action, "receipt");
assert.equal(imported.newCategory, true);
assert.equal(imported.receipt?.merchant, "Lunch");
assert.equal(imported.details, undefined, "Receipt details are stored once");
const receipt = { ...details, importId: extraction.importId, fingerprint: extraction.fingerprint, method: "ai" as const, documentKind: "receipt" as const, merchant: "Old title" };
assert.equal(entryPayload(values, { ...entry, receipt }).receipt?.importId, receipt.importId);
assert.equal(entryPayload({ kind: "transfer", date: values.date, amount: "1" }).details, undefined);
assert.deepEqual(walletPayload({ name: "Cash", amount: "0" }, data.wallets[1]), { name: "Cash", amount: "0", action: "wallet", id: "cash", newCategory: false });

const suggestion = { rate: "2", rateDate: "2026-10-01", provider: "ecb" as const, lastCheckedAt: now.toISOString(), stale: false };
assert.deepEqual(transferConversion("10", true, null, suggestion), { rate: "2", received: "20.00", source: "ecb", referenceDate: "2026-10-01", error: "" });
assert.equal(transferConversion("10", false, null, null).received, "10.00");
assert.equal(transferConversion("10", true, null, null).received, "");
assert.equal(transferConversion("10", true, { mode: "rate", rate: "3", source: "manual" }, suggestion).received, "30.00");
assert.equal(transferConversion("10", true, { mode: "rate", rate: "0", source: "manual" }, null).error, "Exchange rate must be greater than zero.");
const received = transferConversion("10", true, { mode: "received", received: "25", source: "received" }, suggestion);
assert.equal(received.rate, "2.5");
assert.equal(received.received, "25");
assert.equal(received.error, "");
const transfer: Entry = { ...entry, kind: "transfer", received: 2500, exchangeRate: { value: "2.01", source: "ecb", referenceDate: "2026-09-30" } };
const override = initialTransferFields(data, transfer, "IDR", "USD", "bank").override!;
assert.equal(initialTransferFields(data, undefined, "IDR", "USD", "bank").chargedTo, "destination");
const withFee = { ...data, entries: [transfer, { ...entry, id: "fee", transferId: transfer.id, wallet: "bank", currency: "IDR" as const, amount: 50 }] };
assert.equal(initialTransferFields(withFee, transfer, "IDR", "USD", "bank").feeAmount, "0.50");
assert.equal(initialTransferFields(withFee, transfer, "IDR", "USD", "bank").chargedTo, "source");
assert.equal(initialTransferFields(withFee, transfer, "USD", "IDR", "bank").chargedTo, "destination");
assert.equal(transferConversion("12.34", true, override, suggestion).rate, "2.01", "Keep the saved reference even when it differs from actual received money");
assert.equal(transferConversion("12.34", true, override, suggestion).received, "25.00");
assert.equal(transferConversion("10", true, override, suggestion).rate, "2.5");
assert.equal(transferConversion("10", true, override, suggestion).source, "received");
assert.equal(transferConversion("10", true, override, suggestion).referenceDate, "2026-09-30");
assert.equal(initialTransferFields(data, transfer, "IDR", "IDR", "bank").override, null);
assert.equal(initialTransferFields(data, { ...transfer, exchangeRate: undefined }, "IDR", "USD", "bank").override?.source, "received");
console.log("Ledger editor checks passed: initial values, unconfirmed receipts, wallet/currency collisions, archived categories, timestamp preservation, payload validation and all conversion modes.");
