import assert from "node:assert/strict";
import { emptyLedger, mutateLedger, balance } from "../src/features/ledger/ledger.ts";
import { ledgerStorageRows, ledgerFromRows, comparableLedger } from "../src/features/ledger/storage.ts";
import { ledgerQuery, searchPattern, safeAggregate } from "../src/features/ledger/query.ts";

let data = mutateLedger(emptyLedger(), { action: "wallet", name: "Bank", currency: "IDR", amount: "1000" });
data = mutateLedger(data, { action: "wallet", name: "Cash", currency: "USD", amount: "0" });
data = mutateLedger(data, { action: "entry", kind: "transfer", date: "2026-10-01T00:00:00.123Z", wallet: data.wallets[0].id, currency: "IDR", amount: "100", toWallet: data.wallets[1].id, toCurrency: "USD", received: "1", feeAmount: "0.1", feeChargedTo: "destination", description: "" });
const fee = data.entries.find((entry) => entry.transferId)!;
const removed = data.categories.find((category) => category.name === fee.category)!;
data = mutateLedger(data, { action: "deleteCategory", id: removed.id });
const rows = ledgerStorageRows("user", data);
const rebuilt = ledgerFromRows(rows.wallets, rows.categories, rows.entries, rows.imports);
assert.deepEqual(comparableLedger(rebuilt), comparableLedger(data));
assert.equal(rows.categories.find((category) => category.name === fee.category)?.archived, true);
assert.ok(rows.entries.find((entry) => entry.id === fee.id)?.categoryId);
assert.equal(rows.entries.find((entry) => entry.kind === "transfer")?.originalDate, "2026-10-01T00:00:00.123Z");
assert.equal(balance(rebuilt, data.wallets[1].id, "USD"), 90);
assert.equal(balance({ ...rebuilt, entries: [], balanceTotals: { [data.wallets[1].id]: { USD: 90 } } }, data.wallets[1].id, "USD"), 90);
assert.throws(() => ledgerStorageRows("user", { ...data, entries: [...data.entries, data.entries[0]] }), /Duplicate ledger identifiers/);
assert.throws(() => ledgerStorageRows("user", { ...data, entries: [{ ...fee, wallet: "someone-elses-wallet" }] }), /Invalid stored wallet reference/);
assert.throws(() => ledgerStorageRows("user", { ...data, entries: [{ ...fee, transferId: "missing" }] }), /Invalid stored transfer reference/);
assert.equal(searchPattern("  10%_\\  "), "%10\\%\\_\\\\%");
assert.equal(safeAggregate("9007199254740991"), Number.MAX_SAFE_INTEGER);
assert.throws(() => safeAggregate("9007199254740992"), /Balance exceeds/);
assert.throws(() => ledgerQuery({ start: "2026-10-02", end: "2026-10-01" }, "UTC", "IDR"));
assert.throws(() => ledgerQuery({ month: "2026-10" }, "Invalid/Zone", "IDR"));
assert.equal(ledgerQuery({ month: "2026-10" }, "Asia/Jakarta", "IDR", { page: "9007199254740992" }).page, 1);
assert.equal(ledgerQuery({ month: "2026-10" }, "UTC", "IDR", { page: "9" }).page, 9);
console.log("Ledger storage checks passed: lossless conversion, archived categories, exact money/timestamps, ownership, linked transfers, and safe queries.");
