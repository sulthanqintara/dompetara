import assert from "node:assert/strict";
import { QueryClient } from "@tanstack/react-query";
import { ledgerQueryAffected, patchTransactionCache, patchOverviewCache } from "../src/features/ledger/cache.ts";
import { updateLedgerCache } from "../src/features/ledger/update-ledger-cache.ts";
import { ledgerQuery } from "../src/features/ledger/query.ts";
import type { Entry } from "../src/features/ledger/ledger.ts";
import type { LedgerState } from "../src/features/ledger/api.ts";

const query = ledgerQuery({ month: "2026-10" }, "Asia/Jakarta", "IDR", { scope: "summary" });
const entry: Entry = { id: "e", kind: "expense", date: "2026-10-10T00:00:00Z", wallet: "bank", currency: "IDR", amount: 100, title: "Lunch", category: "Dining", description: "" };
const data = { wallets: [{ id: "bank", name: "Bank", currencies: ["IDR"] as const }], categories: [], entries: [] };
const saved: LedgerState = { data: { ...data, wallets: [{ ...data.wallets[0], currencies: ["IDR"] }] }, version: 2,
  changes: { before: [entry], after: [{ ...entry, title: "Dinner", amount: 200 }], invalidateTransactions: false } };
const transactions = { query, version: 1, result: { rows: [entry], related: [entry], total: 1, page: 1, pages: 1, start: 1, end: 1 } };
const patched = patchTransactionCache(transactions, saved);
assert.equal(patched.result.rows[0].title, "Dinner"); assert.equal(patched.result.total, 1);
assert.equal(transactions.result.rows[0].title, "Lunch", "Confirmed cache updates are immutable");
const deleted = patchTransactionCache(transactions, { ...saved, changes: { ...saved.changes!, after: [] } });
assert.equal(deleted.result.rows.length, 0); assert.equal(deleted.result.total, 0); assert.equal(deleted.result.start, 0);
const search = { ...transactions, query: { ...query, search: "Lunch" } };
assert.equal(patchTransactionCache(search, saved).result.rows.length, 0, "Edits stop matching the old search immediately");
assert.equal(patchTransactionCache(search, saved).result.total, 0);
const report = { query: { ...query, scope: "report" as const }, version: 1, result: { totals: { income: 0, expense: 100 }, groups: [["Dining", 100] as [string, number]], daily: [{ date: "2026-10-10", amount: 100 }], monthly: [{ date: "2026-10", amount: 100 }] } };
const summary = patchOverviewCache(report, saved);
assert.equal(summary.result.totals.expense, 200); assert.deepEqual(summary.result.groups, [["Dining", 200]]);
assert.equal(summary.result.daily[0].amount, 200); assert.equal(summary.result.monthly[0].amount, 200);
assert.equal(report.result.totals.expense, 100);
const outside = { ...saved, changes: { ...saved.changes!, before: [], after: [{ ...entry, date: "2026-09-01T00:00:00Z" }] } };
assert.equal(ledgerQueryAffected("overview", query, outside), false);
assert.equal(ledgerQueryAffected("overview", report.query, outside), true, "All-history monthly reports refresh for an edit outside the selected month");
assert.equal(ledgerQueryAffected("overview", query, { ...saved, changes: { ...saved.changes!, before: [], after: [{ ...entry, kind: "correction" }] } }), false);
const client = new QueryClient();
client.setQueryData(["ledger", "transactions", query], transactions);
client.setQueryData(["ledger", "overview", report.query], report);
updateLedgerCache(client, saved);
assert.equal(client.getQueryData<typeof transactions>(["ledger", "transactions", query])!.result.rows[0].title, "Dinner");
assert.equal(client.getQueryCache().find({ queryKey: ["ledger", "transactions", query] })!.state.isInvalidated, true);
client.clear();
console.log("Ledger cache checks passed: confirmed immutable row/total/report updates, filtered membership, deletion, selective invalidation, and account cache disposal.");
